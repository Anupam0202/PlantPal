// Generates Cloudflare static-asset headers (apps/web/public/_headers) from vercel.json so both hosts
// send the same CSP and security headers. `--check` fails when the committed file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';

const vercel = JSON.parse(readFileSync('vercel.json', 'utf8'));
const toPattern = (source) => source.replace('(.*)', '*');
const lines = ['# Generated by tools/sync-headers.mjs from vercel.json. Do not edit by hand.', ''];
for (const rule of vercel.headers) {
  lines.push(toPattern(rule.source));
  for (const h of rule.headers) lines.push(`  ${h.key}: ${h.value}`);
  lines.push('');
}
const out = lines.join('\n');
const target = 'apps/web/public/_headers';

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== out) {
    console.error(`${target} is out of date. Run: node tools/sync-headers.mjs`);
    process.exit(1);
  }
  console.log('sync-headers: _headers matches vercel.json');
} else {
  writeFileSync(target, out);
  console.log(`sync-headers: wrote ${target}`);
}
