// Writes migrations/0003_auth.sql: the tables Better Auth and its passkey plugin need, as SQLite DDL.
// Run after upgrading better-auth: `pnpm --filter @plantpal/api auth:migration`. A test fails while it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { getMigrations } from 'better-auth/db/migration';
import { createAuth } from '../src/lib/auth';
import { createD1 } from '../test/d1-shim';

const dir = new URL('../migrations/', import.meta.url);
const d1 = createD1();
for (const f of ['0001_provider_status.sql', '0002_sync.sql'])
  await d1.exec(readFileSync(new URL(f, dir), 'utf8'));
const auth = createAuth({
  database: d1,
  secret: 'x'.repeat(32),
  publicOrigin: 'http://localhost:8787',
  allowedOrigins: [],
});
const { compileMigrations } = await getMigrations(auth.options);
const sql = (await compileMigrations()).trim();
writeFileSync(
  new URL('0003_auth.sql', dir),
  `-- Better Auth accounts, sessions and passkeys. Generated by scripts/auth-migration.ts; do not edit.\n${sql}\n`,
);
console.log('wrote migrations/0003_auth.sql');
